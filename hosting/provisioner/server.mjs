// CocoBot instance provisioner — runs on your VPS (not cPanel).
//
// The cPanel billing site calls this over HTTPS when a subscription becomes
// active (POST /provision) or leaves active (POST /deprovision). It runs one
// CocoBot container per customer behind Caddy, which serves each customer's
// subdomain over HTTPS with an auto-provisioned Let's Encrypt certificate.
//
// See README.md for VPS setup. Node built-ins only; needs Docker + Caddy.

import { createServer } from "node:http";
import { execFileSync } from "node:child_process";
import { createHash, timingSafeEqual } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const CONFIG = {
  port: Number(process.env.PROVISIONER_PORT ?? 9000),
  listen: process.env.PROVISIONER_LISTEN ?? "127.0.0.1",
  sharedSecret: process.env.PROVISIONER_SHARED_SECRET ?? "",
  domain: process.env.COCO_DOMAIN ?? "cocobot.example.com", // customer subdomains live under this
  image: process.env.COCO_IMAGE ?? "ghcr.io/a1computerinc2026/cocobot:latest",
  stateFile: process.env.PROVISIONER_STATE ?? "/var/lib/cocobot-provisioner/state.json",
  caddyFragment: process.env.CADDY_FRAGMENT ?? "/etc/caddy/conf.d/cocobot-installs.caddyfile",
  reloadCmd: (process.env.CADDY_RELOAD ?? "systemctl reload caddy").split(" "),
  portRangeStart: Number(process.env.PROVISIONER_PORT_START ?? 9100),
  portRangeEnd: Number(process.env.PROVISIONER_PORT_END ?? 9999),
};

const TIERS = ["starter", "personal", "pro", "max"];

if (!CONFIG.sharedSecret) {
  console.error("PROVISIONER_SHARED_SECRET is required");
  process.exit(1);
}

function sh(cmd, args) {
  return execFileSync(cmd, args, { encoding: "utf8" });
}

function slugFor(email) {
  return "coco-" + createHash("sha256").update(String(email).toLowerCase()).digest("hex").slice(0, 12);
}

function loadState() {
  if (!existsSync(CONFIG.stateFile)) return { instances: {} };
  try {
    return JSON.parse(readFileSync(CONFIG.stateFile, "utf8"));
  } catch {
    return { instances: {} };
  }
}

function saveState(state) {
  mkdirSync(dirname(CONFIG.stateFile), { recursive: true });
  writeFileSync(CONFIG.stateFile, JSON.stringify(state, null, 2));
}

function portFree(port, state) {
  if (Object.values(state.instances).some((i) => i.port === port)) return false;
  try {
    const used = execFileSync("docker", ["ps", "--format", "{{.Ports}}"], { encoding: "utf8" });
    if (used.split("\n").some((line) => line.includes(`:${port}->`))) return false;
  } catch { /* docker not ready; rely on state alone */ }
  return true;
}

function allocatePort(state) {
  for (let port = CONFIG.portRangeStart; port <= CONFIG.portRangeEnd; port += 1) {
    if (portFree(port, state)) return port;
  }
  throw new Error("no free port in range");
}

// Rewrites the Caddy fragment from state and reloads Caddy so new subdomains
// get an HTTPS certificate and removed ones stop serving.
function writeCaddyAndReload(state) {
  const lines = [
    "# Generated by cocobot-provisioner. Do not edit by hand.",
    "",
  ];
  for (const inst of Object.values(state.instances)) {
    lines.push(`${inst.slug}.${CONFIG.domain} {`);
    lines.push(`\tencode zstd gzip`);
    lines.push(`\treverse_proxy 127.0.0.1:${inst.port}`);
    lines.push("}");
    lines.push("");
  }
  mkdirSync(dirname(CONFIG.caddyFragment), { recursive: true });
  writeFileSync(CONFIG.caddyFragment, lines.join("\n"));
  try {
    execFileSync(CONFIG.reloadCmd[0], CONFIG.reloadCmd.slice(1));
  } catch (error) {
    console.error("caddy reload failed:", error.message);
  }
}

function provision(email, plan) {
  if (!TIERS.includes(plan)) plan = "pro";
  const state = loadState();
  const slug = slugFor(email);
  const existing = Object.values(state.instances).find((i) => i.slug === slug);
  if (existing) return existing;

  const port = allocatePort(state);
  const name = slug;
  try { execFileSync("docker", ["rm", "-f", name]); } catch { /* not present */ }
  const env = [
    "-e", "OMB_CLOUD_ROLE=home",
    "-e", `OMB_PUBLIC_URL=https://${slug}.${CONFIG.domain}`,
    "-e", "OMB_PORT=8799",
  ];
  sh("docker", [
    "run", "-d",
    "--name", name,
    "--restart", "unless-stopped",
    "-p", `127.0.0.1:${port}:8799`,
    "-v", `${name}-data:/data`,
    ...env,
    CONFIG.image,
  ]);
  const inst = { slug, port, plan, email, container: name, created_at: new Date().toISOString() };
  state.instances[email.toLowerCase()] = inst;
  saveState(state);
  writeCaddyAndReload(state);
  return inst;
}

function deprovision(email) {
  const state = loadState();
  const key = email.toLowerCase();
  const inst = state.instances[key];
  if (!inst) return { removed: false };
  try { execFileSync("docker", ["rm", "-f", inst.container]); } catch { /* already gone */ }
  delete state.instances[key];
  saveState(state);
  writeCaddyAndReload(state);
  return { removed: true, slug: inst.slug };
}

function list() {
  const state = loadState();
  return Object.values(state.instances);
}

function json(res, code, value) {
  const body = JSON.stringify(value);
  res.writeHead(code, { "content-type": "application/json", "content-length": Buffer.byteLength(body) });
  res.end(body);
}

function authorized(req) {
  const provided = String(req.headers["x-provisioner-key"] ?? "");
  const expected = CONFIG.sharedSecret;
  const a = Buffer.from(provided);
  const b = Buffer.from(expected);
  return a.length === b.length && timingSafeEqual(a, b);
}

const MAX_BODY_BYTES = 64 * 1024;
async function readBody(req) {
  const chunks = [];
  let length = 0;
  for await (const chunk of req) {
    length += chunk.length;
    if (length > MAX_BODY_BYTES) throw new Error("body too large");
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString("utf8");
}

const server = createServer(async (req, res) => {
  if (!authorized(req)) return json(res, 401, { error: "unauthorized" });

  if (req.method === "GET" && req.url === "/instances") {
    return json(res, 200, { instances: list() });
  }
  if (req.method === "POST" && req.url === "/provision") {
    try {
      const body = JSON.parse((await readBody(req)) || "{}");
      if (!body.email) return json(res, 400, { error: "email required" });
      const inst = provision(body.email, body.plan ?? "pro");
      return json(res, 200, { ok: true, instance: inst });
    } catch (error) {
      return json(res, 500, { error: error.message });
    }
  }
  if (req.method === "POST" && req.url === "/deprovision") {
    try {
      const body = JSON.parse((await readBody(req)) || "{}");
      if (!body.email) return json(res, 400, { error: "email required" });
      return json(res, 200, { ok: true, ...deprovision(body.email) });
    } catch (error) {
      return json(res, 500, { error: error.message });
    }
  }
  return json(res, 404, { error: "not_found" });
});

server.listen(CONFIG.port, CONFIG.listen, () => {
  console.log(`cocobot-provisioner listening on ${CONFIG.listen}:${CONFIG.port} for *.${CONFIG.domain}`);
});